local entities = require("rpg.domain.entities")
local art = require("rpg.infrastructure.art")
local controller_module = require("rpg.presentation.controller")
local render = require("rpg.presentation.render")
local fixture = require("support.controller_fixture")
local helpers = require("support.helpers")
local T = require("support.test")

local GROUP = "unit/controller"

local View, PAGE_SIZE = controller_module.View, controller_module.PAGE_SIZE
local ItemInstance = entities.ItemInstance
local any, has, starts_with = fixture.any, fixture.has, fixture.starts_with

T.test(GROUP, "name validation and editing", function()
	local controller = fixture.new_controller()
	controller:press("2")
	controller:press("1")
	T.eq(controller.view, View.NAME)
	controller:press("enter")
	T.eq(controller.message, controller:t("new_run.name_invalid"))
	fixture.type_text(controller, "Abcdefghijklmnopqrstuvwxyz")
	T.eq(controller.input_buffer, "Abcdefghijklmnop")
	controller:press("backspace")
	T.eq(controller:input_prompt(), "> Abcdefghijklmno_")
	controller:press("escape")
	T.eq(controller.view, View.DIFFICULTY)
	controller:press("0")
	T.eq(controller.view, View.TITLE)
end)

T.test(GROUP, "title without save has no continue", function()
	local controller = fixture.new_controller()
	T.no(any(fixture.option_keys(controller), function(key)
		return key == "1"
	end))
	controller:press("1")
	T.eq(controller.view, View.TITLE)
	controller:press("0")
	T.ok(controller.exit_requested)
end)

