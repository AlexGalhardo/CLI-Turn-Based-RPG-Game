T.test(GROUP, "merchant menus", function()
	local controller = fixture.new_controller()
	fixture.start_run(controller)
	local session = controller.session
	T.ok(session ~= nil)
	T.eq(controller:title(), controller:t("merchant.title_start"))
	local player = session:state().player
	controller:press("2")
	T.eq(controller:body_lines(), { controller:t("merchant.empty_bag") })
	controller:press("0")
	player.bag[#player.bag + 1] = ItemInstance.new({ uid = 900, item_id = "hand_axe", rarity = "rare", tier = 0 })
	player.bag[#player.bag + 1] = ItemInstance.new({ uid = 901, item_id = "bow", rarity = "common", tier = 0 })
	controller:press("3")
	local labels = fixture.option_labels(controller)
	T.ok(any(labels, function(label)
		return has(label, "Hand Axe")
	end))
	T.no(any(labels, function(label)
		return has(label, "Bow")
	end))
	controller:press("1")
	T.eq(controller.view, View.COMPARE)
	controller:press("1")
	T.eq(controller.view, View.EQUIPMENT)
	-- The reference reads the first equipped slot; a warrior starts with a weapon only.
	local equipped_uid = player.equipment.weapon.uid
	T.ok(equipped_uid == 900 or equipped_uid == 1)
	controller:press("0")
	controller:press("2")
	local sell_keys = fixture.option_keys(controller)
	T.eq(sell_keys[#sell_keys], "0")
	controller:press(sell_keys[1])
	controller:press("0")
	controller:press("4")
	T.eq(#controller:options(), #session:state().merchant_stock + 1)
	player.gold = 0
	controller:press("1")
	T.eq(controller.message, controller:t("error.not_enough_gold"))
	controller:press("0")
	controller:press("1")
	controller:press("1")
	controller:press("enter")
	T.eq(controller.view, View.BUY_POTIONS)
	controller:press("0")
	controller:press("5")
	T.eq(controller.view, View.CHARACTER)
	T.ok(any(controller:body_lines(), function(line)
		return has(line, "Equipment")
	end))
end)

T.test(GROUP, "battle submenus and messages", function()
	local controller = fixture.new_controller()
	fixture.start_run(controller, { vocation_key = "3" })
	controller:press("0")
	T.eq(controller.view, View.BATTLE)
	T.ok(controller:monster_view() ~= nil)
	T.ok(controller:player_view() ~= nil)
	local session = controller.session
	T.ok(session ~= nil)
	local potions = session:state().player.potions
	for potion_id in pairs(potions) do
		potions[potion_id] = nil
	end
	controller:press("3")
	T.eq(controller:body_lines(), { controller:t("battle.no_potions") })
	controller:press("0")
	session:state().player.mp = 0
	controller:press("2")
	controller:press(render.list_key(0))
	T.eq(controller.message, controller:t("error.not_enough_mana"))
	controller:press("escape")
	controller:press("4")
	local cues = controller.animation_cues
	T.ok(#cues == 0 or (#cues == 1 and cues[1] == "attack"), "unexpected cues " .. T.show(cues))
	controller:press("q")
	T.eq(controller.view, View.TITLE)
	T.eq(controller.session, nil)
end)

T.test(GROUP, "bestiary paging and reveal", function()
	local controller = fixture.new_controller()
	local repository = controller.services.repositories.profile
	local profile = repository:load()
	profile.bestiary.rat = { kills = 9, first_killed_at = "2026-01-01T00:00:00Z" }
	profile.bestiary.bat = { kills = 1, first_killed_at = "2026-01-01T00:00:00Z" }
	repository:save(profile)
	controller:press("4")
	local lines = controller:body_lines()
	T.eq(#lines, PAGE_SIZE + 2)
	T.ok(any(lines, function(line)
		return starts_with(line, "Rat") and has(line, "weak")
	end))
	T.ok(any(lines, function(line)
		return starts_with(line, "Bat") and not has(line, "weak")
	end))
	controller:press("n")
	T.ne(controller:body_lines(), lines)
	for _ = 1, 50 do
		controller:press("n")
	end
	local last_page = controller:body_lines()
	T.ok(starts_with(last_page[#last_page], "Page 12/12"), last_page[#last_page])
	controller:press("p")
	controller:press("0")
	controller:press("3")
	T.eq(controller:body_lines(), { controller:t("hall.empty") })
	controller:press("0")
	controller:press("5")
	local achievements = controller:body_lines()
	for index = 1, PAGE_SIZE do
		T.ok(starts_with(achievements[index], "[ ]"), achievements[index])
	end
end)

