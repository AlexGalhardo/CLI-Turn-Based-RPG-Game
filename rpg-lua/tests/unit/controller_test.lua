	T.eq(render.list_index("!"), nil)
end)

T.test(GROUP, "art parsing", function()
	local animations = art.parse_art("@idle\n a\n%%\n b\n@hurt\n x\n")
	T.eq(animations, { idle = { { " a" }, { " b" } }, hurt = { { " x" } } })
	T.eq(art.frame_for(animations, "idle", 3), { " b" })
	T.eq(art.frame_for(animations, "attack", 0), { " a" })
	T.eq(art.frame_for({}, "idle", 0), {})
	T.raises("ValueError", function()
		art.parse_art("oops")
	end, "before")
	T.raises("ValueError", function()
		art.parse_art("%%")
	end, "separator")
	local data = helpers.data()
	local library = art.ArtLibrary.new(helpers.shared_dir())
	for _, creatures in ipairs({ data.monsters, data.bosses }) do
		for _, creature in ipairs(creatures) do
			T.ok(#art.frame_for(library:for_creature(creature), "idle", 0) > 0, creature.id)
		end
	end
end)
